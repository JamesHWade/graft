source("tools/experiments/runtime.R")
experiment_prepare(fts = TRUE)
checkout <- normalizePath(".")
source("tools/experiments/roundtrip/host.R")
roundtrip_load(checkout, globalenv())
out <- Sys.getenv("GRAFT_EXPERIMENT_OUTPUT", tempfile("roundtrip-results-"))
dir.create(out, recursive = TRUE, showWarnings = FALSE)
observed <- new.env(parent = emptyenv())
for (backend in c("manifest", "graft")) {
  root <- tempfile(paste0("roundtrip-", backend, "-"))
  dir.create(root)
  run <- function(action) {
    callr::r(
      function(checkout, root, backend, action) {
        source(file.path(checkout, "tools/experiments/roundtrip/host.R"))
        roundtrip_load(checkout, globalenv())
        roundtrip_process(checkout, root, backend, action)
      },
      args = list(checkout, root, backend, action),
      libpath = .libPaths()
    )
  }
  testthat::test_that(
    paste(
      backend,
      "Commons roundtrip preserves generated bytes across fresh workflows"
    ),
    {
      original <- run("produce")
      unchanged <- run("consume")
      store <- artifact_store(
        root,
        backend,
        "tools/experiments/artifacts/artifact.data-dict.json"
      )
      withdrawn <- tryCatch(
        {
          artifact_fixture(store, 2L)
          testthat::expect_error(
            roundtrip_admit(store, original$checkpoint$input_basis),
            "Input selection is stale",
            class = "artifact_experiment_error"
          )
          artifact_revoke(store, original$checkpoint$input_basis)
          artifact_read_bytes(artifact_digest_path(
            root,
            "policy",
            original$checkpoint$input_basis
          ))
        },
        finally = artifact_close(store)
      )
      revised <- run("revise")
      testthat::expect_length(
        unique(c(original$pid, unchanged$pid, revised$pid)),
        3L
      )
      testthat::expect_identical(
        original$output_hashes,
        unchanged$output_hashes
      )
      testthat::expect_identical(
        original$checkpoint$output_basis,
        unchanged$checkpoint$output_basis
      )
      testthat::expect_equal(original$total, 6)
      testthat::expect_equal(revised$total, 7)
      testthat::expect_match(
        original$report,
        "Synthetic total: 6",
        fixed = TRUE
      )
      testthat::expect_match(revised$report, "Synthetic total: 7", fixed = TRUE)
      store <- artifact_store(
        root,
        backend,
        "tools/experiments/artifacts/artifact.data-dict.json"
      )
      tryCatch(
        {
          old <- artifact_read_basis(
            store,
            original$checkpoint$output_basis,
            consult = FALSE
          )
          testthat::expect_identical(
            vapply(old, function(item) artifact_hash(item$bytes), character(1)),
            original$output_hashes
          )
          testthat::expect_error(
            roundtrip_admit(store, original$checkpoint$input_basis),
            class = "artifact_experiment_error"
          )
          artifact_revoke(store, revised$checkpoint$output_basis)
          testthat::expect_error(
            artifact_read_basis(
              store,
              revised$checkpoint$output_basis,
              "later artifact use"
            ),
            class = "artifact_experiment_error"
          )
          testthat::expect_length(
            artifact_read_basis(
              store,
              revised$checkpoint$output_basis,
              consult = FALSE
            ),
            length(revised$output_hashes)
          )
          testthat::expect_identical(
            artifact_read_bytes(artifact_digest_path(
              root,
              "policy",
              original$checkpoint$input_basis
            )),
            withdrawn
          )
          artifact_fixture(store, 1L)
          testthat::expect_length(
            artifact_review(store, original$checkpoint$input_basis),
            0L
          )
          testthat::expect_error(
            roundtrip_admit(store, original$checkpoint$input_basis),
            "Selection is not eligible",
            class = "artifact_experiment_error"
          )
          observed[[backend]] <- list(
            original_total = original$total,
            revised_total = revised$total,
            retained_objects = length(original$output_hashes),
            separate_processes = TRUE,
            calculation_tag = original$checkpoint$generated$tag,
            output_draft_requires_host_approval = TRUE
          )
        },
        finally = artifact_close(store)
      )
    }
  )
  unlink(root, recursive = TRUE)
}
jsonlite::write_json(
  as.list(observed),
  file.path(out, "roundtrip.json"),
  pretty = TRUE,
  auto_unbox = TRUE
)
cat(
  "Both Commons artifact roundtrips passed. Evidence:",
  file.path(out, "roundtrip.json"),
  "\n"
)
